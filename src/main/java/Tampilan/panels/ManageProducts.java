    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int n = jTable1.getSelectedRow();
        if (n == -1) {
            return;
        }

        btnEdit.setEnabled(true);
        btnHapus.setEnabled(true);

        int id = Integer.parseInt(jTable1.getValueAt(n, 0).toString());

        // Ambil data lengkap dari DB untuk menghindari error parsing DECIMAL
        try {
            Connection K = Koneksi.Go();
            PreparedStatement PS = K.prepareStatement("SELECT * FROM produk WHERE id_produk = ?");
            PS.setInt(1, id);
            ResultSet RS = PS.executeQuery();

            if (RS.next()) {
                selectedProduk = new Produk();
                selectedProduk.setId(RS.getInt("id_produk"));
                selectedProduk.setKodeProduk(RS.getString("kode_produk"));
                selectedProduk.setNama(RS.getString("nama_produk"));
                selectedProduk.setKategori(RS.getString("kategori"));
                selectedProduk.setStok(RS.getInt("stok"));
                selectedProduk.setHargaBeli(RS.getBigDecimal("harga_beli"));
                selectedProduk.setHargaJual(RS.getBigDecimal("harga_jual"));
                selectedProduk.setImagePath(RS.getString("image_path"));
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal mengambil detail produk: " + e.getMessage());
            return;
        }

        // Tampilkan gambar di preview
        String imagePath = selectedProduk.getImagePath();
        if (imagePath != null && !imagePath.isEmpty()) {
            try {
                ImageIcon icon = new ImageIcon(getClass().getResource(imagePath));
                Image img = icon.getImage().getScaledInstance(lblImagePreview.getWidth(), lblImagePreview.getHeight(), Image.SCALE_SMOOTH);
                lblImagePreview.setIcon(new ImageIcon(img));
                lblImagePreview.setText("");
            } catch (Exception e) {
                lblImagePreview.setIcon(null);
                lblImagePreview.setText("Gambar tidak ditemukan");
            }
        } else {
            lblImagePreview.setIcon(null);
            lblImagePreview.setText("Tidak ada gambar");
        }
    }//GEN-LAST:event_jTable1MouseClicked

    public static void RefreshData() {
        try {
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0); 

            Connection K = Koneksi.Go();
            Statement S = K.createStatement();
            // Ambil semua kolom
            String Q = "SELECT * FROM produk";
            ResultSet R = S.executeQuery(Q);

            while (R.next()) {
                // Sesuaikan dengan kolom tabel JTable (6 kolom)
                Object[] dataProduk = {
                    R.getInt("id_produk"),
                    R.getString("kode_produk"),
                    R.getString("nama_produk"),
                    R.getString("kategori"),
                    R.getInt("stok"),
                    R.getBigDecimal("harga_jual") // Tampilkan harga jual
                };
                model.addRow(dataProduk);
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Gagal memuat data produk: " + e.getMessage());
        }
    }

