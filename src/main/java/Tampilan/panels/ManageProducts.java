    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        if (selectedProduk == null) {
            JOptionPane.showMessageDialog(this, "Pilih produk yang ingin dihapus.");
            return;
        }

        int response = JOptionPane.showConfirmDialog(this,
                "Anda yakin ingin menghapus produk '" + selectedProduk.getNama() + "'?",
                "Konfirmasi Hapus",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);

        if (response == JOptionPane.YES_OPTION) {
            try {
                Connection K = Koneksi.Go();
                String sql = "DELETE FROM produk WHERE id_produk = ?";
                PreparedStatement PS = K.prepareStatement(sql);
                PS.setInt(1, selectedProduk.getId());
                PS.executeUpdate();

                // Hapus file gambar
                if (selectedProduk.getImagePath() != null && !selectedProduk.getImagePath().isEmpty()) {
                    File imgFile = new File("src/main/resources" + selectedProduk.getImagePath());
                    if (imgFile.exists()) {
                        imgFile.delete();
                    }
                }
                
                RefreshData(); 
                JOptionPane.showMessageDialog(this, "Produk berhasil dihapus.");

            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Gagal menghapus produk: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnHapusActionPerformed

